// VaultMesh modification: generate branding assets from the existing extension.
// Upstream licenses remain in force. This is not a dependency/build migration.
import { createRequire } from "node:module";
import { readFile, writeFile, readdir, mkdir, copyFile } from "node:fs/promises";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const reference = resolve(root, "../browser-extension/public");
const require = createRequire(import.meta.url);
const sharp = require(process.env.VAULTMESH_SHARP_MODULE || "sharp");
const source = await readFile(resolve(reference, "icon.svg"), "utf8");
const mark = source.slice(source.indexOf("<svg"));
const lock = '<circle cx="790" cy="790" r="148" fill="#f8fafc" stroke="#312e81" stroke-width="12"/><path d="M738 770v-42a52 52 0 0 1 104 0v42" fill="none" stroke="#312e81" stroke-width="25"/><rect x="715" y="768" width="150" height="115" rx="22" fill="#312e81"/><circle cx="790" cy="816" r="16" fill="#fff"/>';
const locked = mark.replace("</svg>", `${lock}</svg>`);
const badge = '<circle cx="210" cy="810" r="116" fill="#f59e0b" stroke="#fff" stroke-width="10"/><text x="210" y="858" text-anchor="middle" font-family="sans-serif" font-size="150" font-weight="700" fill="#171441">β</text>';
await mkdir(resolve(root, "src/branding"), { recursive: true });
await copyFile(resolve(reference, "icon.svg"), resolve(root, "src/images/vaultmesh.svg"));
for (const name of await readdir(resolve(root, "src/images"))) {
  const match = /^icon(\d+)(.*)\.png$/.exec(name);
  if (!match || match[2].includes("safari")) continue;
  const size = Number(match[1]); const variant = match[2];
  // Reuse byte-identical existing assets wherever their sizes already exist.
  if (!variant && [16, 32, 48, 128].includes(size)) {
    await copyFile(resolve(reference, `icon-${size}.png`), resolve(root, "src/images", name));
    continue;
  }
  let svg = variant.includes("locked") ? locked : mark;
  if (variant.includes("beta")) svg = svg.replace("</svg>", `${badge}</svg>`);
  let render = sharp(Buffer.from(svg)).resize(size, size);
  if (variant.includes("gray")) render = render.grayscale();
  await render.png().toFile(resolve(root, "src/images", name));
}
const logo = (color) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 290 48"><title>VaultMesh</title>${mark.replace('<svg ', '<svg x="0" y="0" width="48" height="48" ')}<text x="58" y="35" font-family="system-ui,sans-serif" font-size="34" font-weight="650" fill="${color}">VaultMesh</text></svg>`;
for (const [name, color] of [["logo-dark@2x.png", "#1e1b4b"], ["logo-white@2x.png", "#ffffff"]]) {
  await sharp(Buffer.from(logo(color))).resize(580, 96).png().toFile(resolve(root, "src/popup/images", name));
}
await writeFile(resolve(root, "src/branding/vaultmesh-logo.ts"), `// Generated by scripts/sync-vaultmesh-branding.mjs. Do not edit.\nimport { svg } from "@bitwarden/assets/svg";\nexport const VaultMeshLogo = svg\`${logo("currentColor")}\`;\n`);
await writeFile(resolve(root, "src/branding/vaultmesh-icons.ts"), `// Generated from browser-extension/public/icon.svg. Do not edit.\nexport const vaultMeshIcon = ${JSON.stringify(mark)};\nexport const vaultMeshLockedIcon = ${JSON.stringify(locked)};\n`);

// Only user-facing product strings change. Keys, placeholders, URLs, protocol
// names and names of external Bitwarden products retain their original meaning.
const retained = /(?:web|export|organization|business|families|authenticatorApp|authenticatorPage|secretsManager|selfHosted|marketing|sharedUnlock|twoStepLogin|encryptionKey|download|mobile|secureDevices|continueTo|helpCenter|communityForums|contactSupport|bitwardenSupport|bitwardenAuthenticator|bitwardenForBusiness|moreFromBitwarden)/i;
let locales = 0;
for (const locale of await readdir(resolve(root, "src/_locales"))) {
  const path = resolve(root, "src/_locales", locale, "messages.json");
  const messages = JSON.parse(await readFile(path, "utf8"));
  for (const [key, entry] of Object.entries(messages)) {
    if (typeof entry.message !== "string" || retained.test(key)) continue;
    entry.message = entry.message.replace(/https?:\/\/\S+|Bitwarden/g, (token) => token === "Bitwarden" ? "VaultMesh" : token);
  }
  for (const [key, message] of Object.entries({ appName: "VaultMesh", extName: "VaultMesh", extNameBeta: "VaultMesh Beta", extDesc: locale === "zh_CN" ? "通过浏览器扩展使用 VaultMesh 本地优先密码管理器。" : locale === "zh_TW" ? "透過瀏覽器擴充功能使用 VaultMesh 本機優先密碼管理員。" : "Use VaultMesh securely from the browser popup." })) {
    messages[key] = { ...messages[key], message };
  }
  await writeFile(path, `${JSON.stringify(messages, null, 2)}\n`); locales++;
}
console.log(`VaultMesh branding synchronized: ${locales} locales; assets in ${relative(root, resolve(root, "src/images"))}.`);
